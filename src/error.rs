//! Error type, stable numeric codes and log-safe redaction helpers.

use std::fmt;

use crate::endpoint::Endpoint;

/// SDK result type.
pub type Result<T, E = Error> = std::result::Result<T, E>;

/// Stable SDK error codes, compatible with the original Go SDK mapping.
pub mod code {
    /// Invalid configuration.
    pub const INVALID_CONFIG: i32 = 1001;
    /// Signature verification failed.
    pub const VERIFY_FAILED: i32 = 1003;
    /// The gateway answered with a business error.
    pub const API: i32 = 1004;
    /// Transport failure, unexpected HTTP status or oversized response.
    pub const NETWORK: i32 = 1005;
    /// Successful envelope with an unusable payload.
    pub const INVALID_RESPONSE: i32 = 1006;
    /// Invalid request parameter or notification.
    pub const INVALID_PARAM: i32 = 1007;
}

/// Coarse classification of transport failures.
///
/// Callers use this to decide whether a retry is reasonable. Retrying a
/// mutating call such as [`crate::Client::create_payment`] still requires the
/// application to reason about idempotency of the `out_trade_no`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum TransportErrorKind {
    /// The request or the response body read timed out.
    Timeout,
    /// The TCP or TLS connection could not be established.
    Connect,
    /// A redirect was received and rejected.
    Redirect,
    /// The response body could not be read or decoded.
    Body,
    /// The request could not be built or sent.
    Request,
    /// Any other failure.
    Other,
}

/// EPay SDK error.
///
/// Error text generated by the built-in client never includes a request URL.
/// Response previews are bounded and have `key` / `sign` values masked.
#[derive(Debug, thiserror::Error)]
#[non_exhaustive]
pub enum Error {
    /// Invalid client or protocol configuration.
    #[error("invalid configuration: {0}")]
    Config(&'static str),

    /// Invalid outbound request parameter.
    #[error("invalid parameter: {0}")]
    Param(&'static str),

    /// A notification was malformed, unauthenticated by metadata, or
    /// structurally invalid. Signature mismatches use [`Error::VerifyFailed`].
    #[error("invalid notify: {message}")]
    Notify {
        /// Redacted description of the rejection.
        message: String,
    },

    /// MD5 signature verification failed.
    #[error("signature verification failed")]
    VerifyFailed,

    /// The gateway answered with a non-success `code`.
    #[error("epay API error at {endpoint} (code {code}): {message}")]
    Api {
        /// Endpoint that produced the error.
        endpoint: Endpoint,
        /// Gateway `code` value.
        code: i32,
        /// Gateway `msg` value, redacted.
        message: String,
    },

    /// The HTTP transport failed before a response status was available.
    #[error("HTTP transport error ({kind:?}): {message}")]
    Transport {
        /// Failure classification.
        kind: TransportErrorKind,
        /// Redacted, URL-free description.
        message: String,
    },

    /// The gateway returned a non-2xx status.
    #[error("unexpected HTTP status {status}: {body}")]
    Http {
        /// HTTP status code.
        status: u16,
        /// Redacted preview of the response body.
        body: String,
    },

    /// The gateway reported success but the payload is unusable.
    #[error("invalid response from {endpoint}: {message}")]
    InvalidResponse {
        /// Endpoint that produced the response.
        endpoint: Endpoint,
        /// Redacted description including a bounded body preview.
        message: String,
    },

    /// The response body exceeded the configured limit.
    #[error("response body exceeds configured limit of {limit} bytes")]
    ResponseTooLarge {
        /// Configured limit in bytes.
        limit: usize,
    },
}

impl Error {
    /// Numeric error code, compatible with the original Go SDK mapping.
    pub fn code(&self) -> i32 {
        match self {
            Self::Config(_) => code::INVALID_CONFIG,
            Self::Param(_) | Self::Notify { .. } => code::INVALID_PARAM,
            Self::VerifyFailed => code::VERIFY_FAILED,
            Self::Api { .. } => code::API,
            Self::Transport { .. } | Self::Http { .. } | Self::ResponseTooLarge { .. } => {
                code::NETWORK
            }
            Self::InvalidResponse { .. } => code::INVALID_RESPONSE,
        }
    }

    /// Transport failure classification, if this is a transport error.
    pub fn transport_kind(&self) -> Option<TransportErrorKind> {
        match self {
            Self::Transport { kind, .. } => Some(*kind),
            _ => None,
        }
    }

    /// Whether the failure was a transport timeout.
    pub fn is_timeout(&self) -> bool {
        self.transport_kind() == Some(TransportErrorKind::Timeout)
    }

    /// Whether the request never reached (or never received an answer from)
    /// the gateway's application layer, so repeating it is safe for
    /// read-only endpoints: transport timeouts / connection failures and
    /// HTTP 502/503/504.
    ///
    /// [`crate::RetryPolicy`] consults this. Business errors
    /// ([`Error::Api`]) and malformed responses are never retryable.
    pub fn is_retryable(&self) -> bool {
        match self {
            Self::Transport { kind, .. } => {
                matches!(
                    kind,
                    TransportErrorKind::Timeout | TransportErrorKind::Connect
                )
            }
            Self::Http { status, .. } => matches!(status, 502..=504),
            _ => false,
        }
    }

    /// Build a transport error with a redacted message.
    ///
    /// Custom [`crate::Transport`] implementations should use this rather
    /// than formatting a URL-bearing error into the message.
    pub fn transport(kind: TransportErrorKind, message: impl fmt::Display) -> Self {
        Self::Transport {
            kind,
            message: redact_secrets(&message.to_string()),
        }
    }

    pub(crate) fn notify(message: impl Into<String>) -> Self {
        Self::Notify {
            message: redact_secrets(&message.into()),
        }
    }

    pub(crate) fn api(endpoint: Endpoint, code: i32, message: impl Into<String>) -> Self {
        Self::Api {
            endpoint,
            code,
            message: redact_secrets(&message.into()),
        }
    }

    pub(crate) fn invalid_response(
        endpoint: Endpoint,
        err: impl fmt::Display,
        body: &[u8],
    ) -> Self {
        Self::InvalidResponse {
            endpoint,
            message: format!("{err}: {}", body_preview(body)),
        }
    }

    pub(crate) fn invalid_response_message(endpoint: Endpoint, message: impl Into<String>) -> Self {
        Self::InvalidResponse {
            endpoint,
            message: redact_secrets(&message.into()),
        }
    }

    /// Build an [`Error::Http`] for a non-2xx response, keeping a bounded,
    /// redacted preview of `body`. Custom [`crate::Transport`]s should use
    /// this instead of embedding the raw body.
    pub fn http(status: u16, body: &[u8]) -> Self {
        Self::Http {
            status,
            body: body_preview(body),
        }
    }

    /// Re-sanitize errors returned by custom transports before surfacing them.
    pub(crate) fn sanitized(self) -> Self {
        match self {
            Self::Transport { kind, message } => Self::Transport {
                kind,
                message: redact_secrets(&message),
            },
            Self::Http { status, body } => Self::Http {
                status,
                body: redact_secrets(&body),
            },
            Self::Api {
                endpoint,
                code,
                message,
            } => Self::Api {
                endpoint,
                code,
                message: redact_secrets(&message),
            },
            Self::InvalidResponse { endpoint, message } => Self::InvalidResponse {
                endpoint,
                message: redact_secrets(&message),
            },
            Self::Notify { message } => Self::Notify {
                message: redact_secrets(&message),
            },
            other => other,
        }
    }
}

/// Well-known configuration and parameter errors.
