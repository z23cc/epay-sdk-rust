    /// PID must be greater than zero.
    pub const INVALID_PID: Self = Self::Config("invalid PID: must be greater than 0");
    /// Merchant key must not be empty.
    pub const INVALID_KEY: Self = Self::Config("invalid Key: must not be empty");
    /// API base URL is malformed or carries credentials, query or fragment.
    pub const INVALID_API_URL: Self = Self::Config("invalid API base URL");
    /// API base URL uses plain HTTP without explicit opt-in.
    pub const INSECURE_API_URL: Self = Self::Config(
        "API base URL must use HTTPS; call allow_insecure_http(true) for a legacy HTTP gateway",
    );
    /// `notify_url` is not an absolute HTTP(S) URL.
    pub const INVALID_NOTIFY_URL: Self = Self::Param("notify_url must be an absolute HTTP(S) URL");
    /// `return_url` is not an absolute HTTP(S) URL.
    pub const INVALID_RETURN_URL: Self = Self::Param("return_url must be an absolute HTTP(S) URL");
    /// `notify_url` uses plain HTTP without explicit opt-in.
    pub const INSECURE_NOTIFY_URL: Self = Self::Param(
        "notify_url must use HTTPS; call allow_insecure_callback_http(true) for local testing",
    );
    /// `return_url` uses plain HTTP without explicit opt-in.
    pub const INSECURE_RETURN_URL: Self = Self::Param(
        "return_url must use HTTPS; call allow_insecure_callback_http(true) for local testing",
    );
    /// `out_trade_no` is empty.
    pub const MISSING_OUT_TRADE_NO: Self = Self::Param("out_trade_no is required");
    /// `out_trade_no` violates the accepted charset or length.
    pub const INVALID_OUT_TRADE_NO: Self =
        Self::Param("out_trade_no must be 1..=64 ASCII characters from [A-Za-z0-9._|-]");
    /// Neither the request nor the configuration provides a `notify_url`.
    pub const MISSING_NOTIFY_URL: Self = Self::Param("notify_url is required");
    /// Product `name` is blank.
