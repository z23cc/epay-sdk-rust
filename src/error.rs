    pub const PARAM_TOO_LONG: Self = Self::Param("param exceeds 255 bytes");
    /// `sitename` exceeds [`crate::limits::MAX_SITENAME_BYTES`].
    pub const SITENAME_TOO_LONG: Self = Self::Param("sitename exceeds 64 bytes");
